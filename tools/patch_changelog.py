import io, re, datetime, sys

p = 'CHANGELOG.md'
s = io.open(p, encoding='utf-8', newline='').read()

# ---- 1) 段头时间精确到分钟（按各版本 git 提交时间回填）----
times = {
    'v1.0.0': '2026-09-22 16:31',
    'v1.1.0': '2026-09-22 16:53',
    'v1.2.0': '2026-09-22 17:21',
    'v1.3.0': '2026-09-22 17:40',
    'v1.4.0': '2026-09-22 18:45',
}
for v, t in times.items():
    old = '## [%s] - ' % v
    n = s.count(old)
    assert n == 1, ('header count %s = %d' % (v, n))
    s = s.replace(old, '## [%s] - %s' % (v, t))

now = datetime.datetime.now().strftime('%Y-%m-%d %H:%M')

new_section = u'''## [v1.5.0] - %s

**主题：去掉自绘标题栏（标签条顶到最上面）+ 独立的设置窗口 + 新建标签页秒开**

### 修的bug

1. **Ctrl+1..9 没实现**。README里写着，但代码里根本没有这个键 —— 标签条只有鼠标点击。
   现在补上：`WinEHook` 加 `GotoTabKey`（只在「我们进程是前台」时接管，标准键盘1..9，
   带Shift的不抢），`EmbedForm.GotoTab`切到第N个标签；焦点在我们自己控件上时
   `OnPreviewKeyDown` 也留了一条兜底路径。
2. **标签显示改回一行**（上一轮做成两行是改错了）。标签上只放**文件夹名**，
   完整路径进**悬停提示**；名字和路径一样时（「此电脑」这种）提示里只留一个、不重复两遍。
   标签条高度从44掉回34。
3. **悬停提示的底色/字体没跟颜色模式**。系统那套提示（comctl32）开着视觉样式时经常不认
   `TTM_SETTIPBKCOLOR`，所以改成 `OwnerDraw` 自己画（`Theme.StyleTip`）：
   底色、边框、文字全走我们的调色板，深浅都成立；颜色模式一改，下次弹出来就是新配色。
4. **新建标签页复制了当前标签**。真凶是 `NewTabClicked` / `HotkeyNewTab` / 空白右键三处
   都传了 `CurrentPath()`。改成一律开「此电脑」—— 浏览器的 + 号就是这个意思。
5. **主窗口不区分激活/未激活**（原来永远是设置的那套底色）。现在 `WM_NCACTIVATE` 一到，
   外壳底、标签条底、选中标签底、收藏夹栏底一起换成「失活版」（`Theme.ChromeOff` 等）。
   差值故意做小 —— 我们这几行颜色得和嵌进来的explorer功能区连成一片，差太多反而露接缝。

### 增强

1. **新建标签页不再等一秒多**。日志实测：点 + 到内容出来约1.7秒，其中
   「起explorer进程 + 等它把文件列表建出来」占掉0.8秒左右 —— 这两步跟用户按没按 + 号毫无关系，
   于是提前做掉：每批标签都起完之后，后台（也走串行队列）再起一个**藏着的**备用窗口备着，
   加载完也不显示；一按 + / Ctrl+T 就把它直接显出来，几乎瞬时。用掉立刻再备一个。
   （只在目标是「此电脑」时才用得上 —— 而「新建标签页」现在就是「此电脑」。）
2. **CHANGELOG的时间精确到分钟**（`YYYY-MM-DD HH:MM`），已按各版本的git提交时间回填。

### 新增

1. **开机自启**设置项。写的是当前用户的启动项（`HKCU\\...\\Run` 里一个 `TabbedExplorer` 值，
   不需要管理员权限），启动命令带 `--tray`：只常驻托盘 + 装 Win+E 钩子，**不弹窗口**。
   ⚠ 状态**只认注册表**，不在 `settings.json` 里再存一份 —— 两份状态迟早对不上
   （川自己在「任务管理器 → 启动」里禁用的时候），那时菜单里打的勾就是假的。
   另外每次启动会把启动项里的exe路径刷成现在这个，程序目录被挪过也能对上。
2. **标签页右键新增「复制标签页」**（复制一份同路径的标签）。
3. **独立的设置窗口**。齿轮按钮和标签条空白处右键的「设置」现在开**窗口**，
   里面写程序名、版本、简介，设置项也在里面改；**托盘图标右键那份菜单保持原样**。
   内容不另写一份：窗口和托盘菜单都由 `SettingsMenu.Spec` 渲染
   （同 `Group` 的相邻叶子画成一组单选、单独的叶子画成勾选框、带子项的画成下拉框），
   以后加设置项不会漏一边。

### 评估结论：自绘标题栏去掉了

川问「左上角按钮功能没实现，能不能完整捕获原资源管理器……能实现就可以去掉自己模仿的图标按钮」。

- **原来那条标题栏拿不回来**：嵌进来的explorer是子窗口，子窗口没有非客户区，
  而它的快速访问工具栏恰好画在那一条里 —— 清掉 `WS_CAPTION` 之后那条就空了，
  实测把 `WS_CAPTION` 加回去也毫无变化（顶部那条45px是空的，我们一直在把它裁掉）。
  **所以「完整捕获」做不到。**
- 我们自己仿的那排图标（属性/新建文件夹/撤销/重做/删除/重命名）**确实不灵** ——
  它是「取shell原件的图标 + 把快捷键PostMessage给explorer的焦点窗口」，实测点了没反应。
- 那排图标本来就是多余的：**真正的命令就在嵌进来的explorer自己的功能区里**
  （文件/主页/共享/查看），一模就响。
- **所以：整条自绘标题栏删掉**（`src/TitleBar.cs` 已删除），标签条顶到最上面、多出30像素给内容；
  最小化/最大化还原/关闭三颗并到标签条**最右边**（跟浏览器一样）；
  标签条的**空白处**兼任标题栏 —— 按住拖动可以移动窗口、贴边吸附也白拿
  （超过几个像素才算拖，所以「双击空白 = 新标签」还在）。

### 已知限制

- 嵌进来的explorer是**独立进程**，颜色模式只改得动我们自画的外壳（标签条/收藏夹栏/设置窗口/菜单），
  文件列表仍跟系统 —— 改不了别人进程的开关。
- 「新建标签页秒开」的代价是**多一个藏着的explorer进程**（几十MB）。它是用掉之后才补的，
  程序只驻留托盘、没开过窗口时不会有。

''' % now

# 插在第一个版本段之前
idx = s.index('## [v1.4.0] - ')
s = s[:idx] + new_section + s[idx:]

io.open(p, 'w', encoding='utf-8', newline='').write(s)
print('OK, now =', now)
print('headers:', re.findall(r'^## \[v[0-9.]+\] - .*$', s, re.M))
